"""Authoring source for the five-country golden evaluation set.

Pure data. Expected clauses are anchored on archived source text by a locator
(document title / source URL fragment / clause label / optional text anchor) that
was chosen by reading the source, never by looking at retrieval output. The builder
(`scripts/golden_build.py`) resolves every locator against the live corpus, requires it
to match exactly one clause, and pins the SHA-256 of the original text in the frozen
`golden_cases.json`. Country names, document titles and labels stay in this data layer;
no scoring code branches on them.

Question styles (every topic has all three):
  keyword   - terse keyword query as a compliance officer would type it
  scenario  - business scenario of an automaker in plain language
  datatype  - starts from a concrete data type handled by a connected vehicle
Groups: each topic lists required groups; a group is a list of alternative locators and
counts as found when any alternative is retrieved.
"""

_DIGITS = str.maketrans("0123456789", "٠١٢٣٤٥٦٧٨٩")


def ar(n):
    return str(n).translate(_DIGITS)


def loc(doc, label, url=None, anchor=None, article=None):
    out = {"doc": doc, "label": label}
    if article:
        out["article"] = article  # enables equivalents in a parallel official copy
    if url:
        out["url"] = url
    if anchor:
        out["anchor"] = anchor
    return out


